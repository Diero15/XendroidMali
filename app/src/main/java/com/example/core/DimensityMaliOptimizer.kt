package com.example.core

import android.content.Context
import android.content.SharedPreferences
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow

data class OptimizationProfile(
    val enableMaliTbdr: Boolean = true,
    val enableFp16Precision: Boolean = true,
    val forceSubgroupSize16: Boolean = true,
    val dimensityCorePinning: Boolean = true,
    val turnipDriverBlocker: Boolean = true,
    val renderAreaBackpatching: Boolean = true,
    val asyncPipelineCompilation: Boolean = true,
    val fastMemoryAccessNeon: Boolean = true,
    val resolutionScale: Float = 1.0f,
    val targetFramerate: Int = 60,
    val showDetailedHud: Boolean = true
)

object DimensityMaliOptimizer {

    private const val PREFS_NAME = "xendroid_dimensity_mali_prefs"
    private lateinit var prefs: SharedPreferences

    private val _currentProfile = MutableStateFlow(OptimizationProfile())
    val currentProfile: StateFlow<OptimizationProfile> = _currentProfile.asStateFlow()

    fun init(context: Context) {
        prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        loadFromPrefs()
    }

    private fun loadFromPrefs() {
        if (!::prefs.isInitialized) return
        val profile = OptimizationProfile(
            enableMaliTbdr = prefs.getBoolean("enableMaliTbdr", true),
            enableFp16Precision = prefs.getBoolean("enableFp16Precision", true),
            forceSubgroupSize16 = prefs.getBoolean("forceSubgroupSize16", true),
            dimensityCorePinning = prefs.getBoolean("dimensityCorePinning", true),
            turnipDriverBlocker = prefs.getBoolean("turnipDriverBlocker", true),
            renderAreaBackpatching = prefs.getBoolean("renderAreaBackpatching", true),
            asyncPipelineCompilation = prefs.getBoolean("asyncPipelineCompilation", true),
            fastMemoryAccessNeon = prefs.getBoolean("fastMemoryAccessNeon", true),
            resolutionScale = prefs.getFloat("resolutionScale", 1.0f),
            targetFramerate = prefs.getInt("targetFramerate", 60),
            showDetailedHud = prefs.getBoolean("showDetailedHud", true)
        )
        _currentProfile.value = profile
    }

    fun updateProfile(updater: (OptimizationProfile) -> OptimizationProfile) {
        val newProfile = updater(_currentProfile.value)
        _currentProfile.value = newProfile
        if (::prefs.isInitialized) {
            prefs.edit().apply {
                putBoolean("enableMaliTbdr", newProfile.enableMaliTbdr)
                putBoolean("enableFp16Precision", newProfile.enableFp16Precision)
                putBoolean("forceSubgroupSize16", newProfile.forceSubgroupSize16)
                putBoolean("dimensityCorePinning", newProfile.dimensityCorePinning)
                putBoolean("turnipDriverBlocker", newProfile.turnipDriverBlocker)
                putBoolean("renderAreaBackpatching", newProfile.renderAreaBackpatching)
                putBoolean("asyncPipelineCompilation", newProfile.asyncPipelineCompilation)
                putBoolean("fastMemoryAccessNeon", newProfile.fastMemoryAccessNeon)
                putFloat("resolutionScale", newProfile.resolutionScale)
                putInt("targetFramerate", newProfile.targetFramerate)
                putBoolean("showDetailedHud", newProfile.showDetailedHud)
                apply()
            }
        }
    }

    /**
     * Calculates simulated or expected FPS boost given current profile settings
     */
    fun calculateEstimatedGains(baseFps: Double = 26.0): Pair<Double, Double> {
        var multiplier = 1.0
        val p = _currentProfile.value

        if (p.enableMaliTbdr) multiplier += 0.28 // Prevents TBDR tile flushing bottleneck
        if (p.enableFp16Precision) multiplier += 0.22 // Doubled ALU speed for fragment math
        if (p.forceSubgroupSize16) multiplier += 0.15 // Fixes wave serialization
        if (p.dimensityCorePinning) multiplier += 0.18 // Cortex-X prime core execution
        if (p.renderAreaBackpatching) multiplier += 0.14 // Trims 8192-strip overdraw
        if (p.fastMemoryAccessNeon) multiplier += 0.08 // ARM NEON texture swizzle

        if (p.resolutionScale < 1.0f) multiplier += (1.0f - p.resolutionScale) * 0.35
        else if (p.resolutionScale > 1.0f) multiplier -= (p.resolutionScale - 1.0f) * 0.40

        val estimatedFps = (baseFps * multiplier).coerceIn(10.0, p.targetFramerate.toDouble())
        val estimatedFrameTime = 1000.0 / estimatedFps
        return Pair(estimatedFps, estimatedFrameTime)
    }

    /**
     * Generates TOML config string for Xenia Canary based on Dimensity/Mali settings
     */
    fun generateXeniaConfigToml(): String {
        val p = _currentProfile.value
        return """
# XenDroid Dimensity & ARM Mali Optimized Configuration
# Autogenerated by XenDroid Dimensity Optimization Suite

[GPU]
gpu = "vulkan"
render_target_path_vulkan = "${if (p.enableMaliTbdr) "fbo" else "any"}"
framerate_limit = ${p.targetFramerate}
draw_resolution_scale_x = ${if (p.resolutionScale == 0.75f) 1 else if (p.resolutionScale == 0.5f) 1 else 1}
draw_resolution_scale_y = 1
render_area_dirty_extent = ${p.renderAreaBackpatching}

[Vulkan]
# CRITICAL: Mali GPUs MUST use system libvulkan.so; Turnip only works on Qualcomm Adreno
vulkan_lib_path = "${if (p.turnipDriverBlocker) "" else "/system/lib64/libvulkan.so"}"
vulkan_placeholder_pipelines = ${p.asyncPipelineCompilation}
vulkan_async_skip_draws = ${p.asyncPipelineCompilation}
vulkan_dynamic_pipeline_state = true
vulkan_in_pass_resolve = ${p.enableMaliTbdr}
vulkan_pipeline_creation_threads = 4
vulkan_sparse_shared_memory = false

[Mali_Optimizations]
mali_tbdr_subpass_fusion = ${p.enableMaliTbdr}
mali_fp16_shader_math = ${p.enableFp16Precision}
mali_valhall_subgroup_16 = ${p.forceSubgroupSize16}
neon_fast_memory_copy = ${p.fastMemoryAccessNeon}

[CPU]
cpu = "a64"
dimensity_cortex_x_pinning = ${p.dimensityCorePinning}
thread_priority_urgent = true
""".trimIndent()
    }
}
